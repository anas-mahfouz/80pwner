# 80PWNER — dev tool: regenerate assets/banner.txt (not a runtime dependency).
"""Regenerate the bundled ASCII banner asset.

Usage: .venv/bin/python tools/gen_banner.py
Requires pyfiglet (dev only). The app loads the *static* asset — pyfiglet is
never needed at runtime.
"""
from pathlib import Path

import pyfiglet

FONT = "ansi_shadow"
TEXT = "THE80-PWNER"
OUT = Path(__file__).resolve().parents[1] / "src" / "eightypwner" / "assets" / "banner.txt"


def main() -> None:
    art = pyfiglet.figlet_format(TEXT, font=FONT, width=512)
    left = pyfiglet.figlet_format(TEXT[: TEXT.index("-")], font=FONT, width=512)
    split = max(len(line) for line in left.rstrip().splitlines())
    lines = art.rstrip("\n").splitlines()
    while lines and not lines[-1].strip():
        lines.pop()
    header = (
        "# 80PWNER ASCII banner — generated by pyfiglet, font 'ansi_shadow', text: "
        f"{TEXT}\n"
        f"# two-tone split at column {split} (end of 'THE80'); regenerate with\n"
        "#   python tools/gen_banner.py  (pyfiglet, dev-only)\n"
    )
    OUT.write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    cols = max(len(line) for line in lines)
    print(f"wrote {OUT}: {len(lines)} lines x {cols} cols, split at column {split}")


if __name__ == "__main__":
    main()
