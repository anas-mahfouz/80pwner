# 80PWNER — dev tool: regenerate assets/banner.txt (no runtime dependency).
"""Regenerate the bundled ASCII banner asset from the bitmap font.

Usage: .venv/bin/python tools/gen_banner.py

The art comes from :mod:`eightypwner.ui.banner_font` — a hand-designed 5x7
bitmap font (pyfiglet is NOT used anymore: its ansi_shadow output mixed block
+ box-drawing characters and blurred at scale). Full-block ``█`` cells for
display, with the two-tone split column recorded in the header comment.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from eightypwner.constants import APP_BANNER, BANNER_LEFT
from eightypwner.ui.banner_font import glyph_cols, left_cols, render_text

OUT = Path(__file__).resolve().parents[1] / "src" / "eightypwner" / "assets" / "banner.txt"


def main() -> None:
    art = render_text(APP_BANNER, fill="█")
    split = left_cols(BANNER_LEFT)
    lines = art.splitlines()
    header = (
        "# 80PWNER ASCII banner — bitmap block font (eightypwner/ui/banner_font.py),\n"
        f"# text: {APP_BANNER}; full-block '█' cells; NOT generated by pyfiglet.\n"
        f"# two-tone split at column {split} (end of 'THE80'): left=accent,\n"
        "# right=accent_pressed. Regenerate with:\n"
        "#   python tools/gen_banner.py\n"
    )
    OUT.write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}: {len(lines)} lines x {glyph_cols(len(APP_BANNER))} cols, split at column {split}")


if __name__ == "__main__":
    main()
